import { mkdir, readFile, writeFile } from "node:fs/promises";
import { basename } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = new URL("../../../", import.meta.url);
const generated = new URL("../src/generated/", import.meta.url);

async function bundleArt(kind, sources, width) {
  const folder = new URL(`../../assets/${kind}/`, generated);
  await mkdir(folder, { recursive: true });
  const entries = [];
  for (const [key, source] of sources) {
    const filename = basename(source, ".svg") + ".png";
    const input = fileURLToPath(new URL(`public${source}`, root));
    await sharp(input, { density: 192 })
      .resize({ width })
      .png({ palette: true, colours: 256, dither: 0 })
      .toFile(fileURLToPath(new URL(filename, folder)));
    entries.push(`  ${JSON.stringify(key)}: require("../../assets/${kind}/${filename}"),`);
  }
  const module = [
    "// Generated by scripts/prepare-drawings.mjs",
    "const images: Record<string, number> = {",
    ...entries,
    "};",
    "export default images;",
    "",
  ].join("\n");
  await writeFile(new URL(`${kind}.ts`, generated), module);
  console.log(`Bundled ${entries.length} offline ${kind}.`);
}

const specs = JSON.parse(await readFile(new URL("data/aircraft-drawings.json", root), "utf8"));
const diagrams = Object.entries(specs)
  .filter(([, spec]) => spec.asset)
  .map(([model, spec]) => [model, spec.asset]);
await bundleArt("drawings", diagrams, 1800);
const countries = JSON.parse(await readFile(new URL("data/country-flags.json", root), "utf8"));
const codes = [...new Set(Object.values(countries).flat())].sort();
await bundleArt("flags", codes.map(code => [code, `/flags/${code}.svg`]), 192);
